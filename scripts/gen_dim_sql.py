"""Generate sql/silver/010_dimensions.sql from Urban's codebook (api-variables.json).

Each dimension is a small code -> label lookup table, so gold tables can show words
("City, large") instead of numeric codes. Labels come straight from the codebook:
nothing is typed by hand. Run again after refreshing the codebook.

Usage:
    python scripts/gen_dim_sql.py
"""

from __future__ import annotations

import argparse
import ast
import html
import json
import pathlib
import re
import sys

# silver table -> (codebook variable, one-line description)
DIMENSIONS = {
    "dim_state": ("fips", "State FIPS codes and state names."),
    "dim_grade": ("grade", "Grade codes used in CCD enrollment. 99 is the all-grades total row."),
    "dim_locale": ("urban_centric_locale", "NCES urban-centric locale codes for schools and agencies."),
    "dim_school_level": ("school_level", "School level codes (primary, middle, high, other)."),
    "dim_school_status": (
        "school_status",
        "School status at the start of the school year (open, closed, new...).",
    ),
    "dim_school_type": (
        "school_type",
        "School type codes (regular, special education, vocational, alternative).",
    ),
    "dim_race": ("race", "Race and ethnicity codes. 99 is the all-races total row."),
    "dim_virtual": ("virtual", "Virtual school codes."),
    "dim_title_i_status": ("title_i_status", "Title I status codes. Populated for Virginia 2015-2021 only."),
    "dim_agency_type": ("agency_type", "Agency type codes. 1 = regular local school district."),
}


def clean_label(raw: str) -> str:
    """'11 - City, large' -> 'City, large'; '-1 - Pre-K' -> 'Pre-K'. Unescapes HTML entities."""
    text = html.unescape(raw)
    text = re.sub(r"^\s*-?\d+\s*-\s*", "", text, count=1)
    return " ".join(text.split())


def grade_label(code: int, label: str) -> str:
    """Grades 1-15 arrive labelled just '1' ... '13'; make them readable."""
    if label.isdigit():
        return f"Grade {label}"
    return label


def parse_values(values_text: str) -> dict[int, str]:
    """Parse the codebook's `values` string (a Python dict repr) into {code: label}."""
    parsed = ast.literal_eval(values_text)
    return {int(code): clean_label(label) for code, label in parsed.items()}


def sql_literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def build_dimension_sql(table: str, variable: str, description: str, codes: dict[int, str]) -> str:
    rows = ",\n".join(f"  ({code}, {sql_literal(label)})" for code, label in sorted(codes.items()))
    comment = f"{description} Source: Urban Institute codebook variable '{variable}'."
    return (
        f"CREATE OR REPLACE TABLE silver.{table}\n"
        f"COMMENT {sql_literal(comment)}\n"
        f"AS SELECT * FROM VALUES\n{rows}\n"
        f"AS t(code, label);\n"
    )


def build_file(codebook: dict) -> str:
    variables = {item["variable"]: item for item in codebook["results"]}
    header = (
        "-- GENERATED by scripts/gen_dim_sql.py from docs/codebook/api-variables.json. Do not edit by hand.\n"
        "-- Lookup tables: code -> label, straight from Urban's codebook. Negative codes are the special\n"
        "-- values (-1 missing/not reported, -2 not applicable, -3 suppressed).\n"
    )
    blocks = []
    for table, (variable, description) in DIMENSIONS.items():
        codes = parse_values(variables[variable]["values"])
        if variable == "grade":
            codes = {code: grade_label(code, label) for code, label in codes.items()}
        blocks.append(build_dimension_sql(table, variable, description, codes))
    return header + "\n" + "\n".join(blocks)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate silver dimension SQL from the codebook.")
    parser.add_argument(
        "--codebook", type=pathlib.Path, default=pathlib.Path("docs/codebook/api-variables.json")
    )
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("sql/silver/010_dimensions.sql"))
    args = parser.parse_args(argv)
    codebook = json.loads(args.codebook.read_text(encoding="utf-8"))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(build_file(codebook).encode("utf-8"))
    print(f"wrote {args.out} ({len(DIMENSIONS)} dimension tables)")
    return 0


if __name__ == "__main__":
    exit_code = main()
    if exit_code:
        sys.exit(exit_code)
